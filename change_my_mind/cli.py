app = typer.Typer(no_args_is_help=True)


@app.command()
def serve(host: str = "127.0.0.1", port: int = 8000):
    """Start the local application. Use one worker."""
    from .api import create_app

    # OAuth codes must never appear in HTTP access logs.
    uvicorn.run(create_app(Settings(host=host, port=port)), host=host, port=port, access_log=False)


@app.command()
def trace(port: int = 8002):
    """Open a separate local read-only developer inspector. Does not start model calls."""
    from .developer import serve

    serve(port)


@app.command()
def types(output: Path = Path("frontend/src/api.generated.ts")):
    """Generate TypeScript interfaces from the FastAPI OpenAPI schema."""
    import tempfile

    from .api import create_app

    with tempfile.TemporaryDirectory() as directory:
        application = create_app(Settings(data_dir=Path(directory)))
        schemas = application.openapi()["components"]["schemas"]

    def ts(schema):
        if "$ref" in schema:
            return schema["$ref"].split("/")[-1]
        if "anyOf" in schema:
            return " | ".join(ts(s) for s in schema["anyOf"])
        if "enum" in schema:
            return " | ".join(json.dumps(s) for s in schema["enum"])
        type_ = schema.get("type")
        if type_ == "array":
            return f"Array<{ts(schema['items'])}>"
        if type_ == "object":
            if "properties" in schema:
                required = schema.get("required", [])
                return (
                    "{ "
                    + "; ".join(
                        f"{json.dumps(k)}{'' if k in required else '?'}: {ts(v)}"
                        for k, v in schema["properties"].items()
                    )
                    + " }"
                )
            return (
                "Record<string, "
                + (
                    ts(schema["additionalProperties"])
                    if isinstance(schema.get("additionalProperties"), dict)
                    else "unknown"
                )
                + ">"
            )
        return {
            "string": "string",
            "number": "number",
            "integer": "number",
            "boolean": "boolean",
            "null": "null",
        }.get(type_, "unknown")

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        "// Generated by `uv run change-my-mind types`. Do not edit.\n"
        + "\n".join(f"export type {name} = {ts(schema)};" for name, schema in schemas.items())
        + "\n"
    )
    typer.echo(str(output))


@app.command()
def evaluate(demo: bool = True, budget: float = 15, output: Path = Path("data/evaluation.html")):
    """Explicitly run a comparison suite. Synthetic/offline by default."""

    async def run():
        if not 0.5 <= budget <= 15:
            raise typer.BadParameter(
                "Each topic and the separate suite ceiling must be between $0.50 and $15"
            )
        typer.echo(
            "Synthetic comparison: no API charges."
            if demo
            else f"Paid comparison: original topic up to ${budget:.2f}, plus a separate suite up to ${budget:.2f}; aggregate maximum ${budget * 2:.2f}."
        )
        settings = Settings()
        if not demo and (not settings.allow_paid_api or not settings.openai_api_key):
            raise typer.BadParameter(
                "Paid API evaluation disabled. Explicitly enable DEBATE_ALLOW_PAID_API and set OPENAI_API_KEY to use it."
            )
        store = Store(settings.data_dir)
        await store.initialize()
        jobs = Jobs(store, settings)
        request = RunCreate(
            question=DEMO_QUESTION, model_config={"provider": "demo" if demo else "openai"}, budget_usd=budget
        )
        original = await store.create_run(request)
        await jobs.execute(original)
        parent = await store.get_run(original)
        if parent.status != "completed":
            raise RuntimeError(parent.error)
        suite = await jobs.create_suite(original, "evaluation", budget)
        for child in await store.list_runs():
            if child.config.get("parent_run_id") == original:
                await jobs.execute(child.id)
        await jobs.finalize_suites()
        data = await report_data(store, original)
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(html_report(data))
        typer.echo(
            json.dumps(
                {
                    "original_run": original,
                    "suite_id": suite,
                    "report": str(output.resolve()),
                    "measurement_note": "Citation and correction metrics are inspectable; factual accuracy and usefulness require independent review, not another model's confidence.",
                },
                indent=2,
            )
        )
        await store.close()

    asyncio.run(run())
